package sie.siejuridicos.croma.dto;

import sie.siejuridicos.vigilancia.DocumentoProvidenciaCandidato;
import sie.siejuridicos.vigilancia.dto.ActuacionRegistradaResponse;
import sie.siejuridicos.vigilancia.dto.BoletinJudicialResponse;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.util.List;

public record CromaLegalProResponse(
        boolean exito,
        String mensaje,
        Long casoId,
        String nombreCliente,
        String radicado,
        String fuenteVisible,
        boolean encontradoEnCroma,
        Long idProcesoCpnu,
        Integer connectionIdCroma,
        List<Long> idsProcesosRelacionados,
        boolean soloPrivadoEnRama,
        String codigoDespacho12Digitos,
        String despacho,
        String departamento,
        String sujetosProcesales,
        LocalDate fechaInicio,
        LocalDate fechaUltimaActuacion,
        boolean esPrivado,
        String ponente,
        String tipoProceso,
        String claseProceso,
        String subclaseProceso,
        String recursoProceso,
        String ubicacion,
        String contenidoRadicacion,
        LocalDateTime ultimaActualizacionRama,
        String correoCliente,
        String telefonoCliente,
        String abogadoAsignadoNombre,
        int totalActuaciones,
        int actuacionesNuevasInyectadasEnSie,
        int actuacionesFundamentalesTotal,
        int terminosActivosTotal,
        int boletinesDisponiblesTotal,
        int boletinesNuevosDescargados,
        List<CromaBuzonDespachoDto> buzonesDespacho,
        List<BoletinJudicialResponse> boletinesCacheados,
        List<DocumentoProvidenciaCandidato> documentosEnVivo,
        List<ActuacionRegistradaResponse> actuaciones,
        int creditosConsumidosMes,
        int limiteCreditosMes,
        int consultasRestantesMes,
        boolean cargadoDesdeMemoria,
        OffsetDateTime fechaExtraccionInforme,
        OffsetDateTime fechaExpiracionInforme,
        Integer diasParaBorrarInforme,
        String guardadoHaceTexto
) {
    public static CromaLegalProResponse error(
            String mensaje,
            Long casoId,
            String nombreCliente,
            String radicado,
            int consumidos,
            int limite,
            int restantes) {
        return new CromaLegalProResponse(
                false,
                mensaje,
                casoId,
                nombreCliente,
                radicado,
                null,
                false,
                null,
                null,
                List.of(),
                false,
                null,
                null,
                null,
                null,
                null,
                null,
                false,
                null,
                null,
                null,
                null,
                null,
                null,
                null,
                null,
                null,
                null,
                null,
                0,
                0,
                0,
                0,
                0,
                0,
                List.of(),
                List.of(),
                List.of(),
                List.of(),
                consumidos,
                limite,
                restantes,
                false,
                null,
                null,
                null,
                null
        );
    }

    public CromaLegalProResponse conDatosMemoria(
            boolean desdeMemoria,
            OffsetDateTime fechaExtraccion,
            OffsetDateTime fechaExpiracion,
            int diasParaBorrar,
            String haceTexto,
            int consumidos,
            int limite,
            int restantes) {
        return new CromaLegalProResponse(
                this.exito,
                desdeMemoria
                        ? "Informe cargado desde la memoria de 7 días de Croma (sin consumir créditos). Puedes actualizarlo en vivo si lo deseas."
                        : this.mensaje,
                this.casoId,
                this.nombreCliente,
                this.radicado,
                this.fuenteVisible,
                this.encontradoEnCroma,
                this.idProcesoCpnu,
                this.connectionIdCroma,
                this.idsProcesosRelacionados,
                this.soloPrivadoEnRama,
                this.codigoDespacho12Digitos,
                this.despacho,
                this.departamento,
                this.sujetosProcesales,
                this.fechaInicio,
                this.fechaUltimaActuacion,
                this.esPrivado,
                this.ponente,
                this.tipoProceso,
                this.claseProceso,
                this.subclaseProceso,
                this.recursoProceso,
                this.ubicacion,
                this.contenidoRadicacion,
                this.ultimaActualizacionRama,
                this.correoCliente,
                this.telefonoCliente,
                this.abogadoAsignadoNombre,
                this.totalActuaciones,
                this.actuacionesNuevasInyectadasEnSie,
                this.actuacionesFundamentalesTotal,
                this.terminosActivosTotal,
                this.boletinesDisponiblesTotal,
                this.boletinesNuevosDescargados,
                this.buzonesDespacho,
                this.boletinesCacheados,
                this.documentosEnVivo,
                this.actuaciones,
                consumidos,
                limite,
                restantes,
                desdeMemoria,
                fechaExtraccion,
                fechaExpiracion,
                diasParaBorrar,
                haceTexto
        );
    }
}
